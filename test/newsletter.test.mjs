import { test } from "node:test";
import assert from "node:assert/strict";
import { consumeSignupReceipt } from "../lib/signup-receipt.mjs";
import { subscribe } from "../lib/newsletter.mjs";

const origin = "https://wellspokeninstitute.org";
const env = { TURNSTILE_SECRET: "test", BREVO_API_KEY: "test", BREVO_LIST_ID: "5", BREVO_DOI_TEMPLATE_ID: "2" };
function request(email = "test@example.org", caller = origin) {
  return new Request(origin + "/api/subscribe", { method: "POST", headers: { Origin: caller },
    body: new URLSearchParams({ email, "cf-turnstile-response": "dummy" }) });
}
const valid = { success: true, action: "newsletter", hostname: new URL(origin).hostname };

test("opens double opt-in only after site verification, and redirects without email in the URL", async () => {
  const calls = [];
  const response = await subscribe(request(), env, async (url, init) => {
    calls.push({ url, init });
    return calls.length === 1 ? Response.json(valid) : new Response(null, { status: 201 });
  });
  assert.equal(calls.length, 2);
  assert.equal(calls[0].url, "https://challenges.cloudflare.com/turnstile/v0/siteverify");
  assert.equal(calls[1].url, "https://api.brevo.com/v3/contacts/doubleOptinConfirmation");
  assert.deepEqual(JSON.parse(calls[1].init.body).includeListIds, [5]);
  assert.equal(response.status, 303);
  assert.equal(response.headers.get("Location"), "/thanks?s=1");
  assert.match(response.headers.get("set-cookie"), /Secure/);
});

test("bad input, oversized bodies, origins and missing configuration never reach either service", async () => {
  let count = 0;
  for (const [req, bindings, status] of [[request("bad"), env, 400], [request("x".repeat(9000)), env, 400],
    [request("test@example.org", "https://example.org"), env, 403], [request(), {}, 503]]) {
    assert.equal((await subscribe(req, bindings, () => { count++; })).status, status);
  }
  assert.equal(count, 0);
});

test("rejected tokens and wrong action or hostname never reach the provider", async () => {
  for (const challenge of [{ ...valid, success: false }, { ...valid, hostname: "example.org" }, { ...valid, action: "other" }]) {
    let count = 0;
    assert.equal((await subscribe(request(), env, () => { count++; return Response.json(challenge); })).status, 400);
    assert.equal(count, 1);
  }
});

test("upstream errors never issue a success redirect or receipt", async () => {
  for (const failAt of [1, 2]) {
    let count = 0;
    const response = await subscribe(request(), env, () => ++count === failAt ?
      new Response(null, { status: 503 }) : Response.json(valid));
    assert.equal(response.status, 503);
    assert.equal(response.headers.get("set-cookie"), null);
  }
});

// Run the exact inline script generated by the production Analytics component.
import ts from "typescript";
import React from "react";
import vm from "node:vm";
import fs from "node:fs";
const analyticsSource = fs.readFileSync(new URL("../src/components/Analytics.tsx", import.meta.url), "utf8");
const { outputText } = ts.transpileModule(analyticsSource, { compilerOptions: {
  module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.React, target: ts.ScriptTarget.ES2020,
} });
function countEvents(url, cookie, gaId = "G-TEST123", cloudflare = true) {
  const context = { React, exports: {}, require: () => ({ SITE: { gaId, url: origin } }),
    process: { env: { CF_PAGES: cloudflare ? "1" : "0", NEXT_PUBLIC_TURNSTILE_SITE_KEY: "test" } } };
  vm.runInNewContext(outputText, context);
  const element = context.exports.Analytics();
  const browser = { URL, location: new URL(url), document: { cookie,
    head: { appendChild() {} }, createElement: () => ({ dataset: {} }) },
    history: { replaceState(_state, _title, href) { browser.location = new URL(href); } } };
  browser.window = browser;
  if (element) vm.runInNewContext(element.props.dangerouslySetInnerHTML.__html, browser);
  const validReceipt = consumeSignupReceipt(browser, cloudflare, gaId);
  const repeated = consumeSignupReceipt(browser, cloudflare, gaId);
  assert.equal(repeated, false);
  const events = (browser.dataLayer ?? []).filter((args) => args[1] === "newsletter_signup").length;
  return { validReceipt, events };
}
test("production conversion and pending message both require the function receipt", () => {
  const receipt = "__Host-institute_signup=1";
  const accepted = { validReceipt: true, events: 1 };
  const none = { validReceipt: false, events: 0 };
  assert.deepEqual(countEvents(origin + "/thanks/?s=1", receipt), accepted);
  assert.deepEqual(countEvents(origin + "/thanks", receipt), none);
  assert.deepEqual(countEvents(origin + "/thanks?s=1", ""), none);
  assert.deepEqual(countEvents(origin + "/thanks?confirmed=1", ""), none);
  assert.deepEqual(countEvents(origin + "/thanks?submitted=1", ""), none);
  assert.deepEqual(countEvents(origin + "/thanks?s=1", receipt, "G-TEST123", false), none);
  assert.deepEqual(countEvents("https://example.pages.dev/thanks?s=1", receipt), none);
  assert.deepEqual(countEvents(origin + "/thanks?s=1", receipt, ""), { validReceipt: true, events: 0 });
});
